import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = new URL('../', import.meta.url);
const translatorPath = require.resolve('sinhala-unicode-coverter/lib/cjs/translators/unicode_to_dl_manel.js');
const translator = await readFile(translatorPath, 'utf8');
const source = await readFile(new URL('lib/convert.mjs', root), 'utf8');
const importLine = "import converter from 'sinhala-unicode-coverter/lib/cjs/index.js';";
if (!source.startsWith(importLine)) throw new Error('Converter import changed; update the extension builder.');
// This translator is a standalone CommonJS module. Bundle it in a scoped exports
// object, with the same conversion wrapper as the website. No remote code/eval.
if (/\brequire\s*\(/u.test(translator)) throw new Error('Translator gained dependencies; update the extension builder.');
const wrapper = source.slice(importLine.length).replace(/^export /gm, '');
await writeFile(new URL('extension/converter.js', root), `// Generated by npm run build:extension. See THIRD_PARTY_NOTICES.md.\n(() => {\nconst converter = (() => { const exports = {};\n${translator}\nreturn exports; })();\n${wrapper}\nglobalThis.AkuraConverter = Object.freeze({ toLegacy, toLegacyHtml, legacyRuns });\n})();\n`);
console.log('Ready to load: ' + fileURLToPath(new URL('extension/', root)));
